import { existsSync, readFileSync } from 'node:fs';
import { resolve } from 'node:path';

// Use the project root rather than import.meta.url: Vite rewrites the module URL
// for the bundled build, while Astro always runs from the project root.
const publicDir = resolve(process.cwd(), 'public');

/**
 * Returns the WebP sibling of a published image when one exists, so pages ship
 * the lighter file while frontmatter can keep pointing at the source artwork.
 * Falls back to the original path (and leaves SVG/WebP paths untouched).
 */
export function preferWebp(src?: string): string | undefined {
  if (!src) return src;
  const match = src.match(/^(.*)\.(?:jpe?g|png)$/i);
  if (!match) return src;
  const candidate = `${match[1]}.webp`;
  return existsSync(`${publicDir}${candidate}`) ? candidate : src;
}

export function imageMime(src: string): string {
  const extension = src.split('.').pop()?.toLowerCase();
  if (extension === 'webp') return 'image/webp';
  if (extension === 'png') return 'image/png';
  if (extension === 'svg') return 'image/svg+xml';
  if (extension === 'avif') return 'image/avif';
  return 'image/jpeg';
}

export interface ArticleImage {
  src: string;
  srcSet?: string;
  width: number;
  height: number;
}

let manifestCache: Record<string, { width: number; height: number; webp: string; srcSet: string }> | null = null;

/**
 * Resolves an article photograph to its WebP source, responsive `srcset` and
 * intrinsic dimensions. The manifest is generated by `npm run images:variants`
 * before every build, so mobile browsers can pick a 480/768px file instead of a
 * full-width hero.
 */
export function articleImage(src: string): ArticleImage {
  if (!manifestCache) {
    try {
      const manifestPath = resolve(publicDir, '..', 'src/data/image-manifest.json');
      manifestCache = JSON.parse(readFileSync(manifestPath, 'utf8'));
    } catch {
      manifestCache = {};
    }
  }
  const entry = manifestCache?.[src];
  if (!entry) {
    return { src: preferWebp(src) ?? src, width: 1200, height: 800 };
  }
  return { src: entry.webp, srcSet: entry.srcSet, width: entry.width, height: entry.height };
}
